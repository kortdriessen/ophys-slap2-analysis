function validateTrialResults(E, validTrials, numChannels)
%VALIDATETRIALRESULTS Reject missing or partial high-resolution outputs.

for trialIx = reshape(validTrials, 1, [])
    assert(trialIx <= numel(E) && ~isempty(E{trialIx}), ...
        'slap2:missingTrialResult', ...
        'Trial %d has no extraction result.', trialIx);
    trial = E{trialIx};
    requiredTrialFields = {'footprints', 'dF', 'F0', 'SNR', ...
        'ROIs', 'global', 'discardFrames'};
    assert(all(isfield(trial, requiredTrialFields)), ...
        'slap2:partialTrialResult', ...
        'Trial %d is missing one or more required output fields.', trialIx);
    assert(~isempty(trial.footprints) && ~isempty(trial.SNR), ...
        'slap2:emptyTrialExtraction', ...
        'Trial %d has empty footprints or SNR.', trialIx);

    requiredDfFields = {'events', 'denoised', 'ls'};
    assert(all(isfield(trial.dF, requiredDfFields)), ...
        'slap2:partialDFFResult', ...
        'Trial %d has incomplete dF output.', trialIx);
    for fieldName = requiredDfFields
        values = trial.dF.(fieldName{1});
        assert(size(values,3) == numChannels, ...
            'slap2:savedTraceChannelCount', ...
            'Trial %d dF.%s has %d channels; expected %d.', ...
            trialIx, fieldName{1}, size(values,3), numChannels);
    end
    assert(size(trial.F0,3) == numChannels, ...
        'slap2:savedF0ChannelCount', ...
        'Trial %d F0 has %d channels; expected %d.', ...
        trialIx, size(trial.F0,3), numChannels);
    assert(isfield(trial.global, 'F') && size(trial.global.F,1) == numChannels, ...
        'slap2:partialGlobalResult', ...
        'Trial %d global.F is missing or has the wrong channel axis.', trialIx);
    assert(all(isfield(trial.ROIs, {'F', 'Fsvd'})), ...
        'slap2:partialROIResult', ...
        'Trial %d is missing ROI trace fields.', trialIx);
    if ~isempty(trial.ROIs.F)
        assert(size(trial.ROIs.F,2) == numChannels, ...
            'slap2:savedROIChannelCount', ...
            'Trial %d ROIs.F has the wrong channel axis.', trialIx);
    end
    if ~isempty(trial.ROIs.Fsvd)
        assert(size(trial.ROIs.Fsvd,2) == numChannels, ...
            'slap2:savedROISVDChannelCount', ...
            'Trial %d ROIs.Fsvd has the wrong channel axis.', trialIx);
    end

    nFrames = size(trial.dF.ls,2);
    assert(size(trial.dF.events,2) == nFrames && ...
        size(trial.dF.denoised,2) == nFrames && ...
        size(trial.F0,2) == nFrames && ...
        numel(trial.discardFrames) == nFrames, ...
        'slap2:trialTimeAxisMismatch', ...
        'Trial %d output time axes do not agree.', trialIx);
end
end
