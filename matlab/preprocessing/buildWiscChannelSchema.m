function schema = buildWiscChannelSchema(numChannels, activityChannel, tauGlu_s, tauCa_s)
%BUILDWISCCHANNELSCHEMA Construct and validate Wisconsin channel metadata.

contract = channelContract(numChannels, activityChannel);
assert(numChannels == 2, 'slap2:wiscSchemaChannelCount', ...
    'wisc_raw_channel_v1 requires exactly two physical raw channels.');
assert(activityChannel == 2, 'slap2:wiscSchemaActivityChannel', ...
    'wisc_raw_channel_v1 requires raw channel 2 as the activity channel.');

schema.schemaVersion = 'wisc_raw_channel_v1';
schema.rawChannelNumbers = contract.rawChannelOrder;
schema.analysisChannelOrder = contract.analysisChannelOrder;
schema.activityRawChannel = activityChannel;
schema.indicatorByRawChannel = {'jRGECO1a', 'iGluSnFR4f'};
schema.signalByRawChannel = {'calcium', 'glutamate'};
schema.savedTraceOrder = 'raw';
schema.footprintRawChannel = activityChannel;
schema.snrRawChannel = activityChannel;
schema.kernelTauByRawChannel_s = [tauCa_s, tauGlu_s];

assert(isequal(schema.rawChannelNumbers, [1 2]) && ...
    isequal(schema.analysisChannelOrder, [2 1]) && ...
    schema.footprintRawChannel == schema.activityRawChannel && ...
    schema.snrRawChannel == schema.activityRawChannel && ...
    strcmp(schema.signalByRawChannel{schema.activityRawChannel}, 'glutamate') && ...
    schema.kernelTauByRawChannel_s(1) == tauCa_s && ...
    schema.kernelTauByRawChannel_s(2) == tauGlu_s, ...
    'slap2:contradictoryChannelSchema', ...
    'The requested Wisconsin channel schema is internally contradictory.');
end
