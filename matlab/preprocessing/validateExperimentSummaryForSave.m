function validateExperimentSummaryForSave(exptSummary)
%VALIDATEEXPERIMENTSUMMARYFORSAVE Validate a summary before publication.

requiredFields = {'E', 'params', 'trialTable', 'dr', 'channelSchema', ...
    'validTrials', 'sources', 'provenance'};
assert(all(isfield(exptSummary, requiredFields)), ...
    'slap2:partialExperimentSummary', ...
    'ExperimentSummary is missing required top-level fields.');

nDMDs = size(exptSummary.E,2);
assert(numel(exptSummary.channelSchema) == nDMDs && ...
    numel(exptSummary.validTrials) == nDMDs && ...
    numel(exptSummary.sources) == nDMDs, ...
    'slap2:summaryDMDCountMismatch', ...
    'Summary DMD-indexed metadata do not have matching lengths.');

for dmdIx = 1:nDMDs
    schema = exptSummary.channelSchema{dmdIx};
    expectedSchema = buildWiscChannelSchema(2, 2, ...
        schema.kernelTauByRawChannel_s(2), ...
        schema.kernelTauByRawChannel_s(1));
    assert(isequaln(schema, expectedSchema), ...
        'slap2:invalidSavedChannelSchema', ...
        'DMD %d has a contradictory or incomplete channel schema.', dmdIx);
    validateTrialResults(exptSummary.E(:,dmdIx), ...
        exptSummary.validTrials{dmdIx}, numel(schema.rawChannelNumbers));

    sourceCount = numel(exptSummary.sources{dmdIx}.R);
    assert(sourceCount > 0, 'slap2:noSavedSources', ...
        'DMD %d has no saved sources.', dmdIx);
    for trialIx = reshape(exptSummary.validTrials{dmdIx}, 1, [])
        assert(size(exptSummary.E{trialIx,dmdIx}.footprints,2) == sourceCount, ...
            'slap2:sourceFootprintCountMismatch', ...
            'DMD %d trial %d source and footprint counts differ.', dmdIx, trialIx);
    end
end

requiredProvenance = {'runIdentifier', 'designation', ...
    'acquisitionIdentifier', 'ophysGit', 'slap2Git', ...
    'matlabVersion', 'startTimestamp', 'endTimestamp'};
assert(all(isfield(exptSummary.provenance, requiredProvenance)), ...
    'slap2:incompleteProvenance', ...
    'ExperimentSummary provenance is incomplete.');
end
